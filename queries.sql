-- ---------- Basic queries on Customers ----------

-- 1. Display all customer records
SELECT * FROM Customers;

-- 2. Display customer names and phone numbers
SELECT name, phone FROM Customers;

-- 3. Find customers from Lucknow
SELECT * FROM Customers WHERE address = 'Lucknow';

-- 4. Sort customers by name
SELECT * FROM Customers ORDER BY name ASC;

-- 5. Display first 10 customers
SELECT * FROM Customers LIMIT 10;

-- 6. Count total customers
SELECT COUNT(*) AS total_customers FROM Customers;

-- 7. Count customers city-wise
SELECT address, COUNT(*) AS total FROM Customers GROUP BY address;

-- 8. Find customers whose name starts with 'A'
SELECT * FROM Customers WHERE name LIKE 'A%';

-- 9. Find unique cities
SELECT DISTINCT address FROM Customers;

-- 10. Update customer address
UPDATE Customers SET address = 'Delhi' WHERE customer_id = 5;

-- 11. Find customers between IDs 10 and 30
SELECT * FROM Customers WHERE customer_id BETWEEN 10 AND 30;

-- ---------- Window functions ----------

-- 12. Rank bookings for each customer based on booking date
SELECT customer_id, booking_id, booking_date,
       RANK() OVER (PARTITION BY customer_id ORDER BY booking_date) AS booking_rank
FROM Bookings;

-- 13. Running total of revenue
SELECT payment_id, amount,
       SUM(amount) OVER (ORDER BY payment_id
                         ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_total
FROM Payments;

-- 14. Moving average of the last 3 payments
SELECT payment_id, amount,
       AVG(amount) OVER (ORDER BY payment_id
                         ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS moving_average
FROM Payments;

-- ---------- Joins ----------

-- 15. Driver details along with assigned bookings
SELECT d.driver_name, b.booking_id
FROM Drivers d
LEFT JOIN Bookings b ON d.driver_id = b.driver_id;

-- 16. Total earnings generated by each driver
SELECT d.driver_name, SUM(p.amount) AS total_earnings
FROM Drivers d
JOIN Bookings b ON d.driver_id = b.driver_id
JOIN Payments p ON b.booking_id = p.booking_id
GROUP BY d.driver_name;
